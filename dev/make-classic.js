#!/usr/bin/env node
/* dev/make-classic.js — regenerates the "Classic" copies of the aesthetics.

   A classic aesthetic is the file pair as it was at git tag `r6-0-baseline`, carried
   alongside the current one so a brand can pick "Classic" or "Current" per aesthetic.
   For every key whose current js/css differs from the tag (and that exists at the tag):

     css/aesthetics/classic/<key>.css   [data-ae="<key>"]  ->  [data-ae="<key>--classic"]
     js/aesthetics/classic/<key>.js     the old file wrapped in an IIFE (its top-level
                                        consts / functions cannot collide with the current
                                        file's globals) with registerAesthetic shadowed by
                                        registerClassicAesthetic('<key>', def) (registry.js),
                                        which registers the def as `<key>--classic`,
                                        classicOf: '<key>'.

   Usage:  node dev/make-classic.js [--tag r6-0-baseline] [--check]
   --check writes nothing and exits 1 when the files on disk are stale or index.html is
   missing a tag. Re-run after changing the tag or when a current aesthetic file is
   added. The generated files are committed; never edit them by hand. */
const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');

const ROOT = path.resolve(__dirname, '..');
const args = process.argv.slice(2);
const tagAt = args.indexOf('--tag');
const TAG = tagAt >= 0 ? args[tagAt + 1] : 'r6-0-baseline';
const CHECK = args.includes('--check');

const git = a => execFileSync('git', a, { cwd: ROOT, encoding: 'utf8', maxBuffer: 64 << 20, stdio: ['ignore', 'pipe', 'ignore'] });
const atTag = p => { try { return git(['show', `${TAG}:${p}`]); } catch (e) { return null; } };
const onDisk = p => { try { return fs.readFileSync(path.join(ROOT, p), 'utf8'); } catch (e) { return null; } };

const keys = fs.readdirSync(path.join(ROOT, 'js/aesthetics'))
  .filter(f => f.endsWith('.js') && f !== 'registry.js')
  .map(f => f.slice(0, -3));

function classicCss(key, src) {
  const re = new RegExp(`\\[data-ae=(["']?)${key}\\1\\]`, 'g');
  // 7e51bfa: highlight words carry the accent marker; carry that into the old rule too.
  const hl = /(\.ab-hl \{ color: var\(--ab-accent-ink\);)(?= (?:\}|text-shadow))/g;
  return src.replace(re, `[data-ae="${key}--classic"]`)
    .replace(hl, '$1 background-image: linear-gradient(transparent 62%, var(--ab-accent-mark, transparent) 62%, var(--ab-accent-mark, transparent) 94%, transparent 94%); -webkit-box-decoration-break: clone; box-decoration-break: clone;');
}

function classicJs(key, src) {
  const banner = `/* GENERATED by dev/make-classic.js from ${TAG}:js/aesthetics/${key}.js. Do not edit.\n   Registers as '${key}--classic' (classicOf: '${key}'); see js/aesthetics/registry.js. */\n`;
  return `${banner}(function () {\nconst registerAesthetic = def => registerClassicAesthetic('${key}', def);\n${src.replace(/\s*$/, '')}\n})();\n`;
}

const out = {};
const classic = [];
for (const key of keys) {
  const jsPath = `js/aesthetics/${key}.js`, cssPath = `css/aesthetics/${key}.css`;
  const oldJs = atTag(jsPath), oldCss = atTag(cssPath);
  if (oldJs == null || oldCss == null) continue;                       // new since the tag
  if (oldJs === onDisk(jsPath) && oldCss === onDisk(cssPath)) continue; // unchanged since the tag
  if (!/registerAesthetic\(/.test(oldJs)) throw new Error(`${key}: no registerAesthetic call`);
  if (/data-ae/.test(oldJs)) throw new Error(`${key}: js mentions data-ae; patch the generator`);
  classic.push(key);
  out[`js/aesthetics/classic/${key}.js`] = classicJs(key, oldJs);
  out[`css/aesthetics/classic/${key}.css`] = classicCss(key, oldCss);
}

let stale = 0;
for (const [p, text] of Object.entries(out)) {
  if (onDisk(p) === text) continue;
  stale++;
  if (!CHECK) { fs.mkdirSync(path.dirname(path.join(ROOT, p)), { recursive: true }); fs.writeFileSync(path.join(ROOT, p), text); }
}

const html = onDisk('index.html') || '';
const missing = [];
for (const key of classic) {
  if (!html.includes(`href="css/aesthetics/classic/${key}.css"`)) missing.push(`<link rel="stylesheet" href="css/aesthetics/classic/${key}.css" />`);
  if (!html.includes(`src="js/aesthetics/classic/${key}.js"`)) missing.push(`<script src="js/aesthetics/classic/${key}.js"></script>`);
}

console.log(`${TAG}: ${classic.length} classic aesthetics: ${classic.join(' ')}`);
console.log(CHECK ? `${stale} stale file(s)` : `wrote ${stale} file(s)`);
if (missing.length) console.log('index.html is missing:\n' + missing.join('\n'));
process.exit(CHECK && (stale || missing.length) ? 1 : 0);
