#!/usr/bin/env python3
"""Logo Studio font prep: fonts/files/*.woff2 -> fonts/woff/*.woff (WOFF 1.0, zlib) and
fonts/logo-manifest.json.

Why: the logo engine (js/logo-engine.js) unwraps fonts in the browser with the built-in
DecompressionStream('deflate'), which can read WOFF 1.0 tables but not WOFF2 (brotli).
The manifest maps {family, style, weight} to a file, read from fonts/fonts.css, with each
variable font's axes read from its fvar table.

Needs fonttools + brotli. Run from anywhere:
  python3 dev/logo-fonts.py
"""
import json
import os
import re
import sys

from fontTools.ttLib import TTFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'fonts', 'files')
OUT = os.path.join(ROOT, 'fonts', 'woff')
CSS = os.path.join(ROOT, 'fonts', 'fonts.css')
MANIFEST = os.path.join(ROOT, 'fonts', 'logo-manifest.json')


def convert():
    os.makedirs(OUT, exist_ok=True)
    count = size = 0
    axes = {}
    for name in sorted(os.listdir(SRC)):
        if not name.endswith('.woff2'):
            continue
        font = TTFont(os.path.join(SRC, name))
        font.flavor = 'woff'
        dest = os.path.join(OUT, name[:-len('.woff2')] + '.woff')
        font.save(dest)
        count += 1
        size += os.path.getsize(dest)
        if 'fvar' in font:
            axes[name[:-len('.woff2')] + '.woff'] = {
                a.axisTag: [round(a.minValue, 3), round(a.defaultValue, 3), round(a.maxValue, 3)]
                for a in font['fvar'].axes}
    return count, size, axes


def manifest(axes):
    css = open(CSS, encoding='utf-8').read()
    entries = []
    for block in re.findall(r'@font-face\s*\{(.*?)\}', css, re.S):
        def prop(p):
            m = re.search(r'(?<![\w-])' + p + r'\s*:\s*([^;]+);', block)
            return m.group(1).strip() if m else None
        fam = prop('font-family').strip('\'"')
        src = re.search(r'url\(([^)]+)\)', prop('src')).group(1).strip('\'"')
        base = os.path.basename(src)[:-len('.woff2')] + '.woff'
        weight = [float(v) for v in (prop('font-weight') or '400').split()]
        e = {'family': fam, 'style': prop('font-style') or 'normal',
             'weight': int(weight[0]) if len(weight) == 1 else [int(weight[0]), int(weight[1])],
             'axes': axes.get(base, {}), 'file': 'woff/' + base}
        entries.append(e)
    entries.sort(key=lambda e: (e['family'], e['style'], e['file']))
    with open(MANIFEST, 'w', encoding='utf-8') as f:
        json.dump({'note': 'Generated by dev/logo-fonts.py; do not edit by hand. '
                           'file is relative to fonts/.', 'fonts': entries}, f, indent=1)
        f.write('\n')
    return entries


if __name__ == '__main__':
    n, size, axes = convert()
    entries = manifest(axes)
    print(f'{n} woff files, {size / 1e6:.2f} MB; {len(entries)} manifest entries, '
          f'{len(axes)} variable fonts', file=sys.stdout)
